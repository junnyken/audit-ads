// Node-only; no dependencies or network. Run explicitly, never from tests.
import { readFile, writeFile } from 'node:fs/promises';
const names = ['registry', 'detail', 'edit', 'review'];
const templates = Object.fromEntries(await Promise.all(names.map(async name => [name, await readFile(new URL(`screens/${name}.html`, import.meta.url), 'utf8')])));
await writeFile(new URL('screens.js', import.meta.url), '// Generated by node build.mjs from screens/*.html.\nwindow.P1_SCREENS = ' + JSON.stringify(templates, null, 2) + ';\n');
